CREATE OR REPLACE VIEW NetrebinAA.tj_events_ut_all AS
SELECT
    timestamp,
    directory_name,
    source_file,
    line_number,
    loaded_at,
    event_name,
    level,
    toFloat64(duration_ms) AS duration_sec,
    p_processName,
    t_computerName,
    accurateCastOrNull(t_connectID, 'UInt32') AS t_connectID,
    usr,
    accurateCastOrNull(dbpid, 'UInt16') AS dbpid,
    accurateCastOrNull(osThread, 'UInt32') AS osThread,
    sessionID,
    accurateCastOrNull(extract(sessionID, '^([0-9]+)(?:[(][0-9]+[)])?$'), 'UInt64') AS sessionID_main,
    accurateCastOrNull(extract(sessionID, '^[0-9]+[(]([0-9]+)[)]$'), 'UInt64') AS sessionID_extra,
    accurateCastOrNull(trans, 'UInt8') AS trans,
    toLowCardinality(func) AS func,
    CAST('', 'LowCardinality(String)') AS module,
    CAST('', 'LowCardinality(String)') AS method,
    CAST(NULL, 'Nullable(Int64)') AS memory,
    CAST(NULL, 'Nullable(UInt64)') AS memoryPeak,
    CAST(NULL, 'Nullable(UInt64)') AS inBytes,
    CAST(NULL, 'Nullable(UInt64)') AS outBytes,
    CAST(NULL, 'Nullable(Float64)') AS cpuTime_sec,
    tableName,
    context,
    sql,
    sdbl,
    planSQLText,
    exception,
    locks,
    waitConnections,
    deadlockConnectionIntersections,
    lkaid,
    lka,
    lkp,
    lkpid,
    lksrc,
    accurateCastOrNull(rows, 'UInt64') AS rows,
    accurateCastOrNull(rowsAffected, 'Int64') AS rowsAffected,
    description,
    data,
    severity,
    category
FROM NetrebinAA.tj_events_ut
UNION ALL
SELECT
    timestamp,
    directory_name,
    source_file,
    line_number,
    loaded_at,
    event_name,
    level,
    duration_sec,
    p_processName,
    t_computerName,
    t_connectID,
    usr,
    dbpid,
    osThread,
    sessionID,
    sessionID_main,
    sessionID_extra,
    trans,
    func,
    module,
    method,
    memory,
    memoryPeak,
    inBytes,
    outBytes,
    cpuTime_sec,
    tableName,
    context,
    sql,
    sdbl,
    planSQLText,
    exception,
    locks,
    waitConnections,
    deadlockConnectionIntersections,
    lkaid,
    lka,
    lkp,
    lkpid,
    lksrc,
    rows,
    rowsAffected,
    description,
    data,
    severity,
    category
FROM NetrebinAA.tj_events_ut_v2;
