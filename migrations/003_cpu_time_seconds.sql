-- Existing v2 installations only: stop daemon and verify legacy cpuTime is UInt64 microseconds.
-- Keep original column for rollback. New parser writes cpuTime_sec explicitly.
ALTER TABLE NetrebinAA.tj_events_ut_v2
    ADD COLUMN IF NOT EXISTS cpuTime_sec Nullable(Float64)
    DEFAULT toFloat64(cpuTime) / 1000000.0 AFTER cpuTime;

